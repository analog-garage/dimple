_jpype_to_wrapper: WeakValueDictionary[int, object] = WeakValueDictionary()

def _register_wrapper(wrapper: object, jpype_obj: object) -> None:
    _jpype_to_wrapper.setdefault(id(jpype_obj), wrapper)

W = TypeVar('W')

def _lookup_wrapper(wrapper_type: Type[W], jpype_obj: object) -> W|None:
    if wrapper := _jpype_to_wrapper.get(id(jpype_obj)):
        assert isinstance(wrapper, wrapper_type), f"{wrapper} is not a {wrapper_type}"
    return cast(W|None, wrapper)


_jpype_wrapper_types: dict[type,type] = {}

WT = TypeVar("WT", bound=type)

def jpype_wrapper(jpype_cls: type) -> Callable[[WT],WT]:
    """
    Decorator used before wrapper classes.

    Arguments:
        jpype_cls: Java wrapper class generated by JPype that is
            wrapped by the decorated class
    """
    def _register(wrapper_cls: WT) -> WT:
        _jpype_wrapper_types[jpype_cls] = wrapper_cls
        return wrapper_cls
    return _register

def _lookup_wrapper_type(jpype_cls: type) -> type|None:
    return _jpype_wrapper_types.get(jpype_cls)

type ValueType = bool|str|int|float

N = TypeVar('N', bound='Node')

@jpype_wrapper(JNode)
class Node(ABC):
    """
    Base node type for Dimple factor graphs.

    IMPLEMENTATION NOTE: Node and its subclasses are implemented
    as wrappers around JPype wrapper classes for the corresponding
    Java implementation class. Except where otherwise indicated,
    all of these classes carry no state other than the pointer to
    the jpype instance. This allows us to avoid having to duplicate
    underlying state.
    """
    __slots__ = ['_jnode']

    def __init__(self, *, jnode: JNode) -> None:
        self._jnode = jnode
        _register_wrapper(self, jnode)

    @classmethod
    def for_jnode(cls: Type[N], jnode: JNode) -> N:
        """
        Return wrapper instance for given node.

        Raises:
            TypeError: if there is no associated wrapper class for
                given jnode object or if wrapper is not a subclass
                of the class this is invoked on.
        """
        if wrapper := _lookup_wrapper(cls, jnode):
            return wrapper
        jnode_cls = type(jnode)
        if wrapper_cls := _lookup_wrapper_type(jnode_cls):
            node: N = Node.__new__(wrapper_cls)
            node._jnode = jnode
            return node
        raise TypeError(f"Cannot find wrapper class for '{jnode_cls}'")

    @property
    def graph(self) -> FactorGraph:
        from .factorgraph import FactorGraph
        jgraph = self._jnode.getContainingGraph()
        print(jgraph)
        return FactorGraph.for_jnode(jgraph) # type: ignore

    @property
    def jnode(self) -> JNode:
        return self._jnode

    @property
    def global_id(self) -> int:
        return self.jnode.getGlobalId()

    @property
    def local_id(self) -> int:
        return self.jnode.getLocalId()

    @property
    def name(self) -> str|None:
        return self.jnode.getName()

    @property
    def uuid(self) -> UUID:
        return UUID(str(self.jnode.getUUID()))

    def __eq__(self, other: Any) -> bool:
        return isinstance(other, Node) and other.jnode == self.jnode


